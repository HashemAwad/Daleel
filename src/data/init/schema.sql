-- Daleel schema. Owner: D.
-- Idempotent: safe to re-run any time (`PYTHONPATH=src python -m data.db`).
-- docker only runs this automatically on an EMPTY volume.
-- Seed data lives in loaders, never here. To add a column later:
--   ALTER TABLE <t> ADD COLUMN IF NOT EXISTS ...;
-- Privacy: the ONLY row that survives a conversation is `metadata`, and it has no
-- id, no timestamp and no session key on purpose.

CREATE EXTENSION IF NOT EXISTS vector;
CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- ---- reference: cazas (districts) ------------------------------------------
CREATE TABLE IF NOT EXISTS cazas (
    name_en text PRIMARY KEY,
    name_ar text,
    name_fr text,
    lat     double precision,   -- unused for now (OSM rows already carry their caza)
    lon     double precision
);

CREATE TABLE IF NOT EXISTS caza_aliases (
    alias_key text PRIMARY KEY, -- normalised spelling: aley / عاليه / 3ale / aaley
    caza      text NOT NULL REFERENCES cazas(name_en) ON UPDATE CASCADE
);

-- ---- procedures (B reads/writes; 1024 dims = bge-m3) ------------------------
-- No vector index on purpose: exact scan is instant under ~1k chunks and has perfect recall.
CREATE TABLE IF NOT EXISTS procedures (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      text NOT NULL,
    content    text NOT NULL,
    url        text NOT NULL,
    checked_on date,
    lang       text CHECK (lang IN ('ar', 'arabizi', 'fr', 'en')),
    embedding  vector(1024)
);

-- ---- facilities (pharmacy | hospital | phc) ---------------------------------
CREATE TABLE IF NOT EXISTS facilities (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         text NOT NULL,
    type         text NOT NULL CHECK (type IN ('pharmacy', 'hospital', 'phc')),
    caza         text REFERENCES cazas(name_en) ON UPDATE CASCADE,
    address      text,
    phone        text,
    lat          double precision,
    lon          double precision,
    source       text,
    source_url   text,
    checked_on   date,
    is_synthetic boolean NOT NULL DEFAULT false,   -- demo/sample rows must be labelled
    CHECK ((lat IS NULL) = (lon IS NULL)),
    CHECK (lat BETWEEN -90 AND 90 AND lon BETWEEN -180 AND 180),
    UNIQUE NULLS NOT DISTINCT (type, name, caza)
);
CREATE INDEX IF NOT EXISTS facilities_type_caza_idx ON facilities (type, caza);

-- ---- drugs ------------------------------------------------------------------
-- A wrong price or a false "free" is a harmful answer. Hence:
--   price NULL = unknown (never 0); is_free NULL = unknown (never coerced to false);
--   strength is matched exactly, never fuzzily.
CREATE TABLE IF NOT EXISTS drugs (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           text NOT NULL,
    name_key       text NOT NULL,         -- normalize(name), same fn at ingest and query time
    strength       text,                  -- "5mg"
    form           text,
    atc            text,
    generics       text[] NOT NULL DEFAULT '{}',
    ingredient_key text,                  -- normalize(active ingredient); joins aliases + free list
    price          numeric(14, 2),
    currency       text NOT NULL DEFAULT 'LBP' CHECK (currency IN ('LBP', 'USD')),
    is_free        boolean,               -- NULL on every row today: no loader sets it until a human confirms the free list
    free_list_date date,
    list_date      date,
    source         text,
    source_url     text,
    checked_on     date,
    is_synthetic   boolean NOT NULL DEFAULT false,
    CHECK (price IS NULL OR price > 0),
    UNIQUE NULLS NOT DISTINCT (name_key, strength, form)
);
CREATE INDEX IF NOT EXISTS drugs_name_key_trgm ON drugs USING gin (name_key gin_trgm_ops);
CREATE INDEX IF NOT EXISTS drugs_ingredient_idx ON drugs (ingredient_key);

CREATE TABLE IF NOT EXISTS drug_aliases (
    alias_key      text PRIMARY KEY,      -- UNUSED today: brand spellings live in data.medicine.ALIASES
    ingredient_key text NOT NULL
);

-- ---- hotlines ---------------------------------------------------------------
CREATE TABLE IF NOT EXISTS hotlines (
    number      text PRIMARY KEY,
    name        text NOT NULL,
    purpose     text NOT NULL,
    verified_on date,                     -- NULL until a human has actually called it
    source_url  text
);

-- ---- transcripts: TEMPORARY, REDACTED text only ------------------------------
-- Deleted by the retention job (idle window + hard 24h TTL).
-- Never log exception text from writes here: Postgres errors can echo the row.
CREATE TABLE IF NOT EXISTS transcripts (
    session_hash text NOT NULL,
    turn         integer NOT NULL,
    role         text NOT NULL CHECK (role IN ('user', 'assistant')),
    text         text NOT NULL,
    outcome      text CHECK (outcome IN ('answered', 'unanswered', 'escalated', 'refused', 'emergency')),
    tool         text CHECK (tool IN ('procedure', 'directory', 'medicine', 'hotline', 'none')),
    lang         text CHECK (lang IN ('ar', 'arabizi', 'fr', 'en')),
    created_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (session_hash, turn)
);
CREATE INDEX IF NOT EXISTS transcripts_created_at_idx ON transcripts (created_at);
-- Unlogged: transcript text is never written to the write-ahead log, so it cannot outlive its
-- DELETE in WAL files. A crash empties the table, which is fine for temporary data.
-- Guarded, because ALTER takes an exclusive lock even when there is nothing to change.
DO $$ BEGIN
    IF (SELECT relpersistence FROM pg_class WHERE oid = 'transcripts'::regclass) <> 'u' THEN
        ALTER TABLE transcripts SET UNLOGGED;
    END IF;
END $$;

-- ---- metadata: the only thing that survives a conversation -------------------
-- lang / outcome are closed sets and caza must be a known caza. topic / subtopic are restricted
-- to a lowercase-word PATTERN (no digits, no spaces), not to a fixed list: the values come from
-- a fixed map in data.transcripts. No id / created_at / session key. (Insertion order could
-- still pair a row with its transcript while that transcript exists.)
CREATE TABLE IF NOT EXISTS metadata (
    topic    text NOT NULL CHECK (topic ~ '^[a-z_]{1,40}$'),
    subtopic text CHECK (subtopic ~ '^[a-z_]{1,40}$'),
    caza     text REFERENCES cazas(name_en) ON UPDATE CASCADE,
    lang     text CHECK (lang IN ('ar', 'arabizi', 'fr', 'en')),
    outcome  text NOT NULL CHECK (outcome IN ('answered', 'unanswered', 'escalated', 'refused', 'emergency')),
    day      date NOT NULL
);
